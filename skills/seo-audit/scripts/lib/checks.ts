const LOCAL_HOST_PATTERN = /^(localhost|127\.0\.0\.1|0\.0\.0\.0|.*\.local|example\.(com|org|net)|yourdomain\.com|your-domain\.com|mysite\.com)$/i;

const pass = (...evidence: string[]): CheckOutcome => ({ status: 'pass', evidence });
const warn = (...evidence: string[]): CheckOutcome => ({ status: 'warn', evidence });
const fail = (...evidence: string[]): CheckOutcome => ({ status: 'fail', evidence });
const skip = (...evidence: string[]): CheckOutcome => ({ status: 'skip', evidence });
const info = (...evidence: string[]): CheckOutcome => ({ status: 'info', evidence });

function pathOf(url: string): string {
  try {
    const parsed = new URL(url);
    return `${parsed.pathname}${parsed.search}` || '/';
  } catch {
    return url;
  }
}

export function normalizeUrl(url: string): string {
  try {
    const parsed = new URL(url);
    parsed.hash = '';
    parsed.hostname = parsed.hostname.toLowerCase();
    if (parsed.pathname.length > 1) parsed.pathname = parsed.pathname.replace(/\/+$/, '');
    return parsed.href;
  } catch {
    return url;
  }
}

const htmlPages = (ctx: AuditContext): Page[] => ctx.pages.filter((page) => page.ok && page.isHtml);

// Applies a per-page test. A problem may be a string, or { problem, soft: true }
// for something worth flagging that should never count as a full failure.
function perPage(
  ctx: AuditContext,
  test: (page: Page) => PageProblem,
  { softOnly = false, homeCritical = true }: { softOnly?: boolean; homeCritical?: boolean } = {},
): CheckOutcome {
  const pages = htmlPages(ctx);
  if (pages.length === 0) return skip('No HTML pages to check');
  const bad: { page: Page; problem: string; soft: boolean }[] = [];
  for (const page of pages) {
    const result = test(page);
    if (!result) continue;
    const problem = typeof result === 'string' ? { problem: result, soft: false } : result;
    bad.push({ page, ...problem });
  }
  if (bad.length === 0) return pass(`All ${pages.length} checked page(s) OK`);

  const hard = bad.filter((entry) => !entry.soft);
  const majority = hard.length / pages.length >= 0.5;
  const homeBad = homeCritical && hard.some((entry) => entry.page.isHome);
  const status = !softOnly && (majority || homeBad) ? 'fail' : 'warn';
  const shown = bad.slice(0, 5).map((entry) => `${pathOf(entry.page.url)}: ${entry.problem}`);
  if (bad.length > 5) shown.push(`...and ${bad.length - 5} more page(s)`);
  return { status, evidence: shown };
}

function duplicates(ctx: AuditContext, valueOf: (page: Page) => string | null, label: string): CheckOutcome {
  const pages = htmlPages(ctx);
  if (pages.length < 2) return skip('Needs at least 2 pages');
  const seen = new Map<string, Page[]>();
  for (const page of pages) {
    const value = valueOf(page);
    if (!value) continue;
    seen.set(value, [...(seen.get(value) ?? []), page]);
  }
  const repeated = [...seen.entries()].filter(([, group]) => group.length > 1);
  if (repeated.length === 0) return pass(`${pages.length} pages, no repeated ${label}`);
  const repeatedPages = repeated.reduce((sum, [, group]) => sum + group.length, 0);
  const evidence = repeated
    .slice(0, 3)
    .map(([value, group]) => `"${value}" on ${group.length} pages: ${group.slice(0, 3).map((p) => pathOf(p.url)).join(', ')}`);
  return { status: repeatedPages / pages.length >= 0.5 ? 'fail' : 'warn', evidence };
}

function blockedCrawlers(ctx: AuditContext, tokens: string[]): string[] {
  return tokens.filter((token) => !isAllowed(ctx.robots.parsed, token, '/'));
}

function parseJsonLd(page: Page): { types: string[]; errors: string[] } {
  const types = new Set<string>();
  const errors: string[] = [];
  const visit = (node: unknown): void => {
    if (Array.isArray(node)) {
      node.forEach(visit);
      return;
    }
    if (!node || typeof node !== 'object') return;
    const record = node as Record<string, unknown>;
    for (const type of [record['@type']].flat()) if (typeof type === 'string') types.add(type);
    if (record['@graph']) visit(record['@graph']);
  };
  for (const block of page.parsed.jsonLd) {
    try {
      visit(JSON.parse(block));
    } catch (error) {
      errors.push((error as Error).message);
    }
  }
  return { types: [...types], errors };
}

