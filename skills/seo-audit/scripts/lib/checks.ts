// fix it, so references/checks.md and the report can never drift apart.
//
// A check returns { status, evidence }. Status is pass, warn, fail, skip or info.
// skip and info never affect the score. A check with "cap" limits the whole score
// when it reports gateFailed, because a site crawlers cannot read should not
// score well just because its other tags are tidy.

