#!/usr/bin/env node
// Generates skills/seo-audit/references/checks.md from the check catalog, so the
// docs cannot drift from the code. Run with: npm run docs

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CATEGORIES, CHECKS } from '../skills/seo-audit/scripts/lib/checks.ts';

export const CHECKS_DOC_PATH = fileURLToPath(new URL('../skills/seo-audit/references/checks.md', import.meta.url));

export function renderChecksDoc(): string {
  const scored = CHECKS.filter((check) => check.weight > 0);
  const total = scored.reduce((sum, check) => sum + check.weight, 0);
  const lines = [
    '# SEO audit checks',
    '',
    '<!-- Generated by scripts/gen-checks-doc.ts. Do not edit by hand. -->',
    '',
    `The audit runs ${CHECKS.length} checks. ${scored.length} are scored and ${CHECKS.length - scored.length} are reported without a score.`,
    '',
    '## How the score works',
    '',
    `Each scored check has a weight, and the weights add up to ${total}. A pass earns the full weight, a warning earns half and a failure earns nothing. Checks that do not apply are left out of the total. The score is the percentage earned.`,
    '',
    'Some failures cap the whole score, so tidy tags cannot hide a site that crawlers cannot read:',
    '',
    ...CHECKS.filter((check) => check.cap).map((check) => `- **${check.id}**: capped at ${check.cap} when ${check.capReason}.`),
    '',
    'Grades: A is 90 or more, B is 75 or more, C is 60 or more, D is 40 or more, and F is anything lower.',
    '',
    'Checks that run on every sampled page fail when the homepage fails or when at least half the pages fail. Otherwise they warn.',
    '',
  ];

  for (const category of CATEGORIES) {
    lines.push(`## ${category}`, '');
    for (const check of CHECKS.filter((item) => item.category === category)) {
      lines.push(
        `### ${check.id}`,
        '',
        `**${check.title}** (${check.weight > 0 ? `weight ${check.weight}` : 'not scored'})`,
        '',
        `Why: ${check.why}`,
        '',
        `Fix: ${check.fix}`,
        '',
      );
    }
  }
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(CHECKS_DOC_PATH, renderChecksDoc());
  console.log(`Wrote ${CHECKS_DOC_PATH}`);
}
